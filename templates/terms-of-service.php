<p>Korzystanie z Aplikacji wymaga rejestracji konta z użyciem adresu e-mail i hasła. Użytkownik zobowiązuje się do:</p>
<ul>
    <li>podania prawdziwego adresu e-mail,</li>
    <li>zachowania poufności danych logowania,</li>
    <li>niezwłocznego poinformowania Operatora o nieautoryzowanym dostępie do konta.</li>
